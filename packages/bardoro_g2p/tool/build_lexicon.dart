/// Builds `assets/en_lexicon.txt` from misaki's `us_gold.json` and `us_silver.json`.
///
/// Usage: `dart run tool/build_lexicon.dart US_GOLD.json US_SILVER.json [OUT]`
/// Gold entries win over silver. Words whose phonemes contain characters outside the internal
/// inventory are skipped and listed on stderr (never silently rewritten).
library;

import 'dart:convert';
import 'dart:io';

import 'package:bardoro_g2p/bardoro_g2p.dart';

void main(List<String> args) {
  if (args.length < 2) {
    stderr.writeln('usage: build_lexicon <us_gold.json> <us_silver.json> [out]');
    exit(64);
  }
  final out = args.length > 2 ? args[2] : 'assets/en_lexicon.txt';
  final allowed = {...phoneInventory, primaryStressMark, secondaryStressMark};
  final lines = <String, String>{};
  var skipped = 0;
  for (final path in [args[1], args[0]]) {
    // silver first, then gold overwrites
    final data = jsonDecode(File(path).readAsStringSync()) as Map<String, dynamic>;
    for (final e in data.entries) {
      final v = e.value;
      final byPos = <String, String>{};
      String? def;
      if (v is String) {
        def = v;
      } else if (v is Map) {
        for (final p in v.entries) {
          if (p.value is! String) continue; // misaki has a few null POS values
          if (p.key == 'DEFAULT') {
            def = p.value as String;
          } else {
            byPos[p.key] = p.value as String;
          }
        }
      }
      if (def == null) continue;
      final all = [def, ...byPos.values];
      if (all.any((s) => s.split('').any((c) => !allowed.contains(c)))) {
        skipped++;
        stderr.writeln('skip ${e.key}: $all');
        continue;
      }
      final cols = [e.key, def, ...byPos.entries.map((p) => '${p.key}=${p.value}')];
      lines[e.key] = cols.join('\t');
    }
  }
  final keys = lines.keys.toList()..sort();
  File(out).writeAsStringSync(
    '# Generated by tool/build_lexicon.dart from misaki us_gold + us_silver (Apache-2.0). See NOTICE.\n'
    '${keys.map((k) => lines[k]).join('\n')}\n',
  );
  stdout.writeln('wrote ${keys.length} entries to $out ($skipped skipped)');
}
